-- Adds the manual delivery checklist marker, initially NOT_STARTED. Java enforces food/Xerox step
-- order; this is not live GPS.
ALTER TABLE campus_jobs ADD COLUMN progress_step VARCHAR(32) NOT NULL DEFAULT 'NOT_STARTED';

-- Stores the delivery handoff code's encoded verifier after helper acceptance. The requester
-- receives the raw code by email; it is cleared on completion.
ALTER TABLE campus_jobs ADD COLUMN completion_otp_hash VARCHAR(100);

-- Optional eight-hour delivery code expiry, checked by Java before completion.
ALTER TABLE campus_jobs ADD COLUMN completion_otp_expires_at VARCHAR(40);

-- Persisted wrong-code count, initially zero; Java blocks handoff after five failed checks.
ALTER TABLE campus_jobs ADD COLUMN completion_otp_attempts INT NOT NULL DEFAULT 0;

-- Private Xerox file data and print options, one attachment per job. Public metadata does not
-- grant access to file_data.
CREATE TABLE job_attachments (
 -- Both primary key and cascading foreign key: permits at most one file per job and deletes it if
 -- the job is deleted.
 job_id BIGINT PRIMARY KEY REFERENCES campus_jobs(id) ON DELETE CASCADE,
 -- Sanitized source filename for display; does not determine whether bytes are safe or permitted.
 original_name VARCHAR(255) NOT NULL,
 -- MIME type inferred by the service from supported file signatures.
 content_type VARCHAR(100) NOT NULL,
 -- Stored byte count with SQL range 1..2097152 (2 MiB).
 file_size BIGINT NOT NULL CHECK(file_size BETWEEN 1 AND 2097152),
 -- Allowed print mode is BLACK_WHITE or COLOR.
 xerox_mode VARCHAR(20) NOT NULL CHECK(xerox_mode IN ('BLACK_WHITE','COLOR')),
 -- Requested print copies constrained to 1..100.
 copies INT NOT NULL CHECK(copies BETWEEN 1 AND 100),
 -- Private PDF/PNG/JPEG bytes in BYTEA. Only job participants can retrieve them through Java
 -- authorization.
 file_data BYTEA NOT NULL
);

-- One available-balance row per user. Withdrawals reserve funds by subtracting from this balance
-- before external payout.
CREATE TABLE wallet_accounts (
 -- Primary key plus cascading user foreign key ensures exactly one possible wallet per account.
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 -- Exact available balance, never negative by CHECK. Pending withdrawals have already been
 -- subtracted/reserved.
 balance DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK(balance >= 0),
 -- Last change time supplied by JPA callbacks or explicit Java SQL updates, depending on the table.
 updated_at VARCHAR(40) NOT NULL
);

-- Wallet ledger recording credits, reserved debits, refunds, and review status. Job offline
-- earnings are separate.
CREATE TABLE wallet_transactions (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Owning application account ID. The foreign key must match an existing users.id.
 user_id BIGINT NOT NULL REFERENCES users(id),
 -- Application ledger category such as WELCOME_CREDIT, TOPUP, WITHDRAWAL, or WITHDRAWAL_REFUND. SQL
 -- has no enum/check on this field.
 kind VARCHAR(32) NOT NULL,
 -- Signed exact decimal: credits/refunds are positive and withdrawal reservations negative. A
 -- rejected debit and its refund remain visible as history.
 amount DECIMAL(12,2) NOT NULL,
 -- Application-maintained ledger status. Unlike request statuses, this column has no SQL
 -- allowed-values CHECK.
 status VARCHAR(20) NOT NULL,
 -- Optional application-level top-up/withdrawal request ID. No foreign key exists because the
 -- target table depends on kind.
 reference_id BIGINT,
 -- Readable audit explanation, bounded to 300 characters.
 note VARCHAR(300) NOT NULL,
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL
);

-- Supports each student's newest ledger rows, using descending ID.
CREATE INDEX ix_wallet_transactions_user ON wallet_transactions(user_id,id DESC);

-- Pending claims about externally paid top-ups. Submitting this row does not credit balance;
-- administrator approval does.
CREATE TABLE wallet_topup_requests (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Owning application account ID. The foreign key must match an existing users.id.
 user_id BIGINT NOT NULL REFERENCES users(id),
 -- Positive top-up amount from 1 through 50000, checked by SQL and service.
 amount DECIMAL(12,2) NOT NULL CHECK(amount BETWEEN 1 AND 50000),
 -- Normalized external payment reference; UNIQUE rejects reuse of the same top-up UTR. It is not
 -- payment-provider confirmation.
 utr VARCHAR(40) NOT NULL UNIQUE,
 -- Optional private screenshot bytes; only the administrator proof endpoint exposes them.
 proof_data BYTEA,
 -- Optional detected image/png or image/jpeg MIME type.
 proof_type VARCHAR(40),
 -- PENDING initially; only APPROVED credits balance, while REJECTED adds no credit.
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 -- Optional reviewing administrator account ID referencing users.id. Java checks that the actor is
 -- an administrator.
 reviewed_by BIGINT REFERENCES users(id),
 -- Optional administrator explanation retained with the review decision.
 review_note VARCHAR(300),
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL,
 -- Optional timestamp set when the administrator records a decision.
 reviewed_at VARCHAR(40)
);

-- Supports review-status lookup/order. The admin query uses CASE to prioritize pending requests;
-- this index is not a guarantee that its entire sort is avoided.
CREATE INDEX ix_wallet_topups_status ON wallet_topup_requests(status,id);

-- Reserved withdrawal requests awaiting manual external payout or rejection/refund.
CREATE TABLE wallet_withdrawal_requests (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Owning application account ID. The foreign key must match an existing users.id.
 user_id BIGINT NOT NULL REFERENCES users(id),
 -- Positive reserved withdrawal amount in the SQL range 1..50000.
 amount DECIMAL(12,2) NOT NULL CHECK(amount BETWEEN 1 AND 50000),
 -- External payout address validated syntactically in the DTO; not a payment instruction to a
 -- gateway.
 upi_id VARCHAR(100) NOT NULL,
 -- PENDING initially; admin later records PAID or REJECTED.
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','PAID','REJECTED')),
 -- Optional outgoing payout reference; Java requires a valid reference before PAID.
 payment_utr VARCHAR(40),
 -- Optional reviewing administrator account ID referencing users.id. Java checks that the actor is
 -- an administrator.
 reviewed_by BIGINT REFERENCES users(id),
 -- Optional administrator explanation retained with the review decision.
 review_note VARCHAR(300),
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL,
 -- Optional timestamp set when the administrator records a decision.
 reviewed_at VARCHAR(40)
);

-- Supports withdrawal status-based access, with ID as the next key.
CREATE INDEX ix_wallet_withdrawals_status ON wallet_withdrawal_requests(status,id);

-- One-time V5 backfill: creates a wallet with INR 100 for every account that already exists when
-- this migration runs. New registrations receive the equivalent credit from WalletService instead.
-- Do not rerun this insert manually.
INSERT INTO wallet_accounts(user_id,balance,updated_at)
 SELECT id,100.00,CAST(CURRENT_TIMESTAMP AS VARCHAR) FROM users;

-- Records the matching completed WELCOME_CREDIT ledger entry for each existing user. Together with
-- the prior insert, this explains the opening balance; it is not a payment-gateway transfer.
INSERT INTO wallet_transactions(user_id,kind,amount,status,note,created_at)
 SELECT id,'WELCOME_CREDIT',100.00,'COMPLETED','One-time JAVAC welcome credit',CAST(CURRENT_TIMESTAMP AS VARCHAR) FROM users;
