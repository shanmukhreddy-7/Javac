-- Login identity and account state, mapped by User. StudentProfile holds the student-facing
-- details separately.
CREATE TABLE users (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Unique normalized login email. NOT NULL and UNIQUE prevent missing/duplicate identities.
 email VARCHAR(254) NOT NULL UNIQUE,
 -- Slow encoded password verifier produced by the configured PBKDF2 PasswordEncoder; not plaintext.
 password_hash VARCHAR(255) NOT NULL,
 -- Stored account role, initially STUDENT; trusted login logic determines administrator status.
 role VARCHAR(20) NOT NULL DEFAULT 'STUDENT',
 -- Starts FALSE and becomes TRUE only after account email ownership verification.
 email_verified BOOLEAN NOT NULL DEFAULT FALSE,
 -- Starts PENDING; Java controls activation/suspension. This column has no SQL CHECK restricting
 -- its text.
 account_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 -- Starts at zero; password changes/moderation increment it to revoke older session principals.
 credential_version BIGINT NOT NULL DEFAULT 0,
 -- Creation time stored as a SQL timestamp, mapped to Java Instant.
 created_at TIMESTAMP(6) NOT NULL,
 -- Last change time supplied by JPA callbacks or explicit Java SQL updates, depending on the table.
 updated_at TIMESTAMP(6) NOT NULL
);

-- One profile per account. Its own id is distinct from user_id; student_skills uses this profile
-- id.
CREATE TABLE student_profiles (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- NOT NULL UNIQUE foreign key gives each account at most one profile. Unlike id, this is the login
 -- account ID.
 user_id BIGINT NOT NULL UNIQUE,
 -- Student display name; distinct from account login email.
 full_name VARCHAR(80) NOT NULL,
 -- Unique university registration identifier, normalized by registration logic.
 registration_number VARCHAR(40) NOT NULL UNIQUE,
 -- Student department text, bounded to 80 characters.
 department VARCHAR(80) NOT NULL,
 -- Academic year; ck_study_year below restricts it to 1 through 6.
 study_year INT NOT NULL,
 -- Optional biography represented by a non-null empty-string default.
 bio VARCHAR(500) NOT NULL DEFAULT '',
 -- Nullable reserved avatar URL; the current profile update/view DTOs do not implement avatar
 -- editing.
 avatar_url VARCHAR(500),
 -- Declared campus preference, default empty text; not a GPS coordinate.
 preferred_location VARCHAR(100) NOT NULL DEFAULT '',
 -- Foreign key enforces an existing related record. With no ON DELETE CASCADE here, dependent rows
 -- normally prevent deleting their parent.
 CONSTRAINT fk_profile_user FOREIGN KEY (user_id) REFERENCES users(id),
 -- Database constraint limits the academic year to the supported 1..6 range.
 CONSTRAINT ck_study_year CHECK (study_year BETWEEN 1 AND 6)
);

-- Shared skill directory mapped by Skill. V2 inserts the initial named entries.
CREATE TABLE skills (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Unique skill label seeded by V2, such as Java.
 name VARCHAR(80) NOT NULL UNIQUE,
 -- Directory group such as Programming or Tutoring.
 category VARCHAR(60) NOT NULL
);

-- Many-to-many join table between profiles and directory skills. Stores relationships, not
-- duplicated skill text.
CREATE TABLE student_skills (
 -- References student_profiles.id, not users.id.
 student_id BIGINT NOT NULL,
 -- References the reusable skills.id directory entry.
 skill_id BIGINT NOT NULL,
 -- Composite primary key prevents selecting the same skill twice for one profile.
 PRIMARY KEY (student_id,skill_id),
 -- Foreign key enforces an existing related record. With no ON DELETE CASCADE here, dependent rows
 -- normally prevent deleting their parent.
 CONSTRAINT fk_student_skill FOREIGN KEY (student_id) REFERENCES student_profiles(id),
 -- Foreign key enforces an existing related record. With no ON DELETE CASCADE here, dependent rows
 -- normally prevent deleting their parent.
 CONSTRAINT fk_skill FOREIGN KEY (skill_id) REFERENCES skills(id)
);

-- Single-use email-verification links mapped by VerificationToken/ExpiringToken. Six-digit account
-- codes are in email_otps instead.
CREATE TABLE email_verification_tokens (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Owning application account ID. The foreign key must match an existing users.id.
 user_id BIGINT NOT NULL,
 -- Unique 64-character SHA-256 lookup hash of a random emailed link token.
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 -- Timestamp after which the link is rejected.
 expires_at TIMESTAMP(6) NOT NULL,
 -- Nullable consumption timestamp; null means unused but does not override expiry.
 used_at TIMESTAMP(6),
 -- Creation time stored as a SQL timestamp, mapped to Java Instant.
 created_at TIMESTAMP(6) NOT NULL,
 -- Foreign key enforces an existing related record. With no ON DELETE CASCADE here, dependent rows
 -- normally prevent deleting their parent.
 CONSTRAINT fk_verification_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- Supports finding one account's verification links and ordering by issue time for
-- cooldown/history.
CREATE INDEX ix_verification_user ON email_verification_tokens(user_id,created_at);

-- Single-use password recovery links mapped by PasswordResetToken/ExpiringToken. Raw emailed
-- tokens are never stored.
CREATE TABLE password_reset_tokens (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Owning application account ID. The foreign key must match an existing users.id.
 user_id BIGINT NOT NULL,
 -- Unique SHA-256 lookup hash of a random password-reset link secret.
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 -- Expiry checked before the service changes any password.
 expires_at TIMESTAMP(6) NOT NULL,
 -- Set when a link is consumed; prevents a second password reset using the same token.
 used_at TIMESTAMP(6),
 -- Creation time stored as a SQL timestamp, mapped to Java Instant.
 created_at TIMESTAMP(6) NOT NULL,
 -- Foreign key enforces an existing related record. With no ON DELETE CASCADE here, dependent rows
 -- normally prevent deleting their parent.
 CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- Supports the corresponding password-reset token history lookup.
CREATE INDEX ix_reset_user ON password_reset_tokens(user_id,created_at);
