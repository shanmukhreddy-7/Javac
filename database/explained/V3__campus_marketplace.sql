-- Marketplace requests handled with JdbcTemplate in MarketplaceService. Requester and helper both
-- refer to users.id.
CREATE TABLE campus_jobs (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Requester account; required users foreign key.
 owner_id BIGINT NOT NULL REFERENCES users(id),
 -- Accepted helper account; nullable while the request remains unassigned.
 helper_id BIGINT REFERENCES users(id),
 -- Short marketplace title; NOT NULL plus bounded length controls storage, while DTO validation
 -- disallows blank text.
 title VARCHAR(120) NOT NULL,
 -- Request details bounded to 2,000 characters.
 description VARCHAR(2000) NOT NULL,
 -- Human-readable category used for directory grouping or marketplace filtering.
 category VARCHAR(40) NOT NULL,
 -- Agreed job reward with two decimal places and SQL range 0..10000. Completing the job does not
 -- credit wallet_accounts.
 reward DECIMAL(10,2) NOT NULL CHECK(reward BETWEEN 0 AND 10000),
 -- Student-entered pickup description, not live positioning.
 pickup VARCHAR(120) NOT NULL,
 -- Student-entered handoff destination.
 destination VARCHAR(120) NOT NULL,
 -- UTC ISO-8601 deadline text parsed/normalized by Java; SQL VARCHAR itself does not validate a
 -- date.
 deadline VARCHAR(40) NOT NULL,
 -- Persisted workflow/review state. DEFAULT initializes new rows; CHECK, where present, restricts
 -- allowed stored values.
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','ACCEPTED','IN_PROGRESS','DELIVERED','COMPLETED','CANCELLED')),
 -- UNPAID or COLLECTED records offline reward collection, independent of wallet review.
 payment_status VARCHAR(20) NOT NULL DEFAULT 'UNPAID' CHECK(payment_status IN ('UNPAID','COLLECTED')),
 -- Nullable external collection label recorded by the helper. No transfer is initiated by storing
 -- it.
 payment_method VARCHAR(20),
 -- Optional ISO-8601 time at which collection was recorded.
 collected_at VARCHAR(40),
 -- FALSE normally; administrator moderation sets TRUE so ordinary listings/details omit the job.
 hidden BOOLEAN NOT NULL DEFAULT FALSE,
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL,
 -- Last change time supplied by JPA callbacks or explicit Java SQL updates, depending on the table.
 updated_at VARCHAR(40) NOT NULL
);

-- Indexes status and creation time for status-filtered listing access; the current browse query
-- also orders by id.
CREATE INDEX ix_jobs_status ON campus_jobs(status,created_at);

-- Supports selecting jobs posted by one requester.
CREATE INDEX ix_jobs_owner ON campus_jobs(owner_id);

-- Supports selecting jobs assigned to one helper, including earnings history.
CREATE INDEX ix_jobs_helper ON campus_jobs(helper_id);

-- Private job conversation records. Participant permission is checked in Java before reads/writes.
CREATE TABLE job_messages (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Associated campus_jobs.id; the job must already exist.
 job_id BIGINT NOT NULL REFERENCES campus_jobs(id),
 -- Account that sent the message; Java verifies it is a participant.
 sender_id BIGINT NOT NULL REFERENCES users(id),
 -- Non-null text bounded to 1,000 characters; the DTO also requires nonblank input.
 body VARCHAR(1000) NOT NULL,
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL
);

-- Groups messages by job and orders by their ID for bounded conversation reads.
CREATE INDEX ix_messages_job ON job_messages(job_id,id);

-- Persisted in-app notifications, scoped to their recipient account. These rows are not SMTP email
-- or mobile push messages.
CREATE TABLE notifications (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Owning application account ID. The foreign key must match an existing users.id.
 user_id BIGINT NOT NULL REFERENCES users(id),
 -- Optional related job; nullable because the schema permits notifications without a job.
 job_id BIGINT REFERENCES campus_jobs(id),
 -- Readable in-app notification text bounded to 300 characters.
 message VARCHAR(300) NOT NULL,
 -- FALSE until the owning student marks this notification read.
 is_read BOOLEAN NOT NULL DEFAULT FALSE,
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL
);

-- Groups notifications by owning user and ID for newest-first personal lists.
CREATE INDEX ix_notifications_user ON notifications(user_id,id);

-- Post-completion feedback between job participants. Java enforces completed status and determines
-- the other participant.
CREATE TABLE job_reviews (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Associated campus_jobs.id; the job must already exist.
 job_id BIGINT NOT NULL REFERENCES campus_jobs(id),
 -- Account writing the feedback.
 reviewer_id BIGINT NOT NULL REFERENCES users(id),
 -- Other job participant receiving the feedback.
 recipient_id BIGINT NOT NULL REFERENCES users(id),
 -- Integer constrained to 1..5 by SQL and DTO validation.
 rating INT NOT NULL CHECK(rating BETWEEN 1 AND 5),
 -- Non-null bounded feedback text; empty comments are allowed by the review DTO.
 comment VARCHAR(500) NOT NULL,
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL,
 -- One review per reviewer per job, enforced even if concurrent requests race past the Java
 -- duplicate check.
 UNIQUE(job_id,reviewer_id)
);

-- Student-submitted moderation reports. Admin resolution and hiding a listing are distinct service
-- operations.
CREATE TABLE job_reports (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Associated campus_jobs.id; the job must already exist.
 job_id BIGINT NOT NULL REFERENCES campus_jobs(id),
 -- Account submitting the moderation report.
 reporter_id BIGINT NOT NULL REFERENCES users(id),
 -- Bounded non-null moderation explanation; DTO validation also requires nonblank text.
 reason VARCHAR(500) NOT NULL,
 -- FALSE until an administrator marks the report resolved; does not itself hide the job.
 resolved BOOLEAN NOT NULL DEFAULT FALSE,
 -- Creation time supplied as text; normal service writes use UTC ISO-8601 Instant strings.
 created_at VARCHAR(40) NOT NULL
);

-- Account ownership/recovery code state keyed by email and purpose. OtpService uses locks and
-- independent transactions for cooldowns/attempt limits.
CREATE TABLE email_otps (
 -- Generated surrogate primary key. IDENTITY lets the database allocate it; PRIMARY KEY makes it
 -- unique and non-null.
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 -- Account email address; callers normalize it before lookup. In email_otps it identifies a
 -- mailbox, without a users foreign key.
 email VARCHAR(254) NOT NULL,
 -- Application purpose such as VERIFY or RESET; participates in the unique mailbox/purpose key.
 purpose VARCHAR(20) NOT NULL,
 -- Local PBKDF2 verifier, or NEON_MANAGED marker when Neon Auth owns code verification. Not a
 -- delivery code.
 code_hash VARCHAR(255) NOT NULL,
 -- Five-minute validity boundary stored as ISO-8601 text.
 expires_at VARCHAR(40) NOT NULL,
 -- Issue timestamp used for the 60-second resend cooldown.
 sent_at VARCHAR(40) NOT NULL,
 -- Persisted check count starting at zero; Java rejects checks at five or more.
 attempts INT NOT NULL DEFAULT 0,
 -- FALSE until successful verification consumes the code. One mailbox/purpose record is replaced on
 -- issuance.
 used BOOLEAN NOT NULL DEFAULT FALSE,
 -- Each mailbox has one current record per purpose. VERIFY and RESET can coexist, while issuance
 -- replaces state for the same pair.
 UNIQUE(email,purpose)
);
